CREATE TABLE departments (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(20)  NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL
);
CREATE TABLE subjects (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          VARCHAR(20)  NOT NULL UNIQUE,
  name          VARCHAR(150) NOT NULL,
  credits       INT NOT NULL,
  semester_no   INT NOT NULL,
  department_id BIGINT NOT NULL REFERENCES departments(id)
);
CREATE TABLE class_groups (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(80) NOT NULL,
  section       VARCHAR(10) NOT NULL,
  semester_no   INT NOT NULL,
  academic_year VARCHAR(20) NOT NULL,
  department_id BIGINT NOT NULL REFERENCES departments(id),
  CONSTRAINT uq_class_name_year UNIQUE (name, academic_year)
);
CREATE TABLE students (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        BIGINT NOT NULL UNIQUE REFERENCES users(id),
  roll_no        VARCHAR(30) NOT NULL UNIQUE,
  department_id  BIGINT NOT NULL REFERENCES departments(id),
  class_group_id BIGINT NOT NULL REFERENCES class_groups(id)
);
CREATE TABLE teachers (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT NOT NULL UNIQUE REFERENCES users(id),
  employee_code VARCHAR(30) NOT NULL UNIQUE,
  department_id BIGINT NOT NULL REFERENCES departments(id)
);
CREATE TABLE teacher_assignments (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id     BIGINT NOT NULL REFERENCES teachers(id),
  subject_id     BIGINT NOT NULL REFERENCES subjects(id),
  class_group_id BIGINT NOT NULL REFERENCES class_groups(id),
  CONSTRAINT uq_assignment UNIQUE (teacher_id, subject_id, class_group_id)
);
CREATE INDEX idx_students_class ON students(class_group_id);
CREATE INDEX idx_assign_class   ON teacher_assignments(class_group_id);
CREATE INDEX idx_assign_teacher ON teacher_assignments(teacher_id);
