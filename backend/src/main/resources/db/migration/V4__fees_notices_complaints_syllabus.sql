CREATE TABLE fees (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id   BIGINT NOT NULL REFERENCES students(id),
  title        VARCHAR(150) NOT NULL,
  total_amount DECIMAL(10,2) NOT NULL,
  late_fee     DECIMAL(10,2) NOT NULL DEFAULT 0,
  due_date     DATE NOT NULL,
  created_at   TIMESTAMP NOT NULL,
  updated_at   TIMESTAMP NOT NULL,
  version      BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_fees_student ON fees(student_id);

CREATE TABLE payments (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fee_id      BIGINT NOT NULL REFERENCES fees(id),
  amount      DECIMAL(10,2) NOT NULL,
  paid_at     TIMESTAMP NOT NULL,
  method      VARCHAR(20) NOT NULL,
  payment_ref VARCHAR(60),
  recorded_by BIGINT NOT NULL REFERENCES users(id),
  created_at  TIMESTAMP NOT NULL
);
CREATE INDEX idx_payments_fee ON payments(fee_id);

CREATE TABLE notices (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       VARCHAR(150)  NOT NULL,
  description VARCHAR(4000) NOT NULL,
  author_id   BIGINT NOT NULL REFERENCES users(id),
  created_at  TIMESTAMP NOT NULL,
  expiry_date DATE,
  priority    VARCHAR(12) NOT NULL,
  target_type VARCHAR(15) NOT NULL,
  target_id   BIGINT
);

CREATE TABLE complaints (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submitted_by BIGINT NOT NULL REFERENCES users(id),
  category     VARCHAR(20)   NOT NULL,
  title        VARCHAR(150)  NOT NULL,
  description  VARCHAR(2000) NOT NULL,
  status       VARCHAR(15)   NOT NULL,
  assigned_to  BIGINT REFERENCES users(id),
  resolution   VARCHAR(1000),
  created_at   TIMESTAMP NOT NULL,
  updated_at   TIMESTAMP NOT NULL,
  resolved_at  TIMESTAMP,
  version      BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_complaints_submitter ON complaints(submitted_by);
CREATE INDEX idx_complaints_assignee ON complaints(assigned_to);

CREATE TABLE syllabus_topics (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id BIGINT NOT NULL REFERENCES subjects(id),
  unit_no    INT NOT NULL,
  title      VARCHAR(200) NOT NULL,
  sort_order INT NOT NULL
);
CREATE INDEX idx_topics_subject ON syllabus_topics(subject_id);

CREATE TABLE syllabus_progress (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  topic_id       BIGINT NOT NULL REFERENCES syllabus_topics(id),
  class_group_id BIGINT NOT NULL REFERENCES class_groups(id),
  completed      BOOLEAN NOT NULL,
  completed_on   DATE,
  updated_by     BIGINT NOT NULL REFERENCES teachers(id),
  updated_at     TIMESTAMP NOT NULL,
  CONSTRAINT uq_syllabus_progress UNIQUE (topic_id, class_group_id)
);
