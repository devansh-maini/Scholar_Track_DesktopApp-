CREATE TABLE attendance_records (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id      BIGINT NOT NULL REFERENCES students(id),
  subject_id      BIGINT NOT NULL REFERENCES subjects(id),
  attendance_date DATE NOT NULL,
  status          VARCHAR(10) NOT NULL,
  marked_by       BIGINT NOT NULL REFERENCES teachers(id),
  created_at      TIMESTAMP NOT NULL,
  updated_at      TIMESTAMP NOT NULL,
  version         BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_attendance UNIQUE (student_id, subject_id, attendance_date)
);
CREATE INDEX idx_att_student ON attendance_records(student_id);
CREATE INDEX idx_att_subject_date ON attendance_records(subject_id, attendance_date);

CREATE TABLE marks (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id      BIGINT NOT NULL REFERENCES students(id),
  subject_id      BIGINT NOT NULL REFERENCES subjects(id),
  assessment_type VARCHAR(20) NOT NULL,
  marks           DECIMAL(6,2) NOT NULL,
  max_marks       DECIMAL(6,2) NOT NULL,
  recorded_by     BIGINT NOT NULL REFERENCES teachers(id),
  created_at      TIMESTAMP NOT NULL,
  updated_at      TIMESTAMP NOT NULL,
  version         BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_marks UNIQUE (student_id, subject_id, assessment_type)
);
CREATE INDEX idx_marks_student ON marks(student_id);

CREATE TABLE assignments (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id     BIGINT NOT NULL REFERENCES subjects(id),
  class_group_id BIGINT NOT NULL REFERENCES class_groups(id),
  teacher_id     BIGINT NOT NULL REFERENCES teachers(id),
  title          VARCHAR(150) NOT NULL,
  description    VARCHAR(2000),
  deadline       TIMESTAMP NOT NULL,
  max_marks      DECIMAL(6,2) NOT NULL,
  created_at     TIMESTAMP NOT NULL
);
CREATE INDEX idx_assignments_class ON assignments(class_group_id);

CREATE TABLE submissions (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id BIGINT NOT NULL REFERENCES assignments(id),
  student_id    BIGINT NOT NULL REFERENCES students(id),
  content       VARCHAR(500) NOT NULL,
  status        VARCHAR(12) NOT NULL,
  submitted_at  TIMESTAMP NOT NULL,
  marks         DECIMAL(6,2),
  feedback      VARCHAR(1000),
  evaluated_at  TIMESTAMP,
  version       BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_submission UNIQUE (assignment_id, student_id)
);
CREATE INDEX idx_submissions_student ON submissions(student_id);

CREATE TABLE semester_results (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id  BIGINT NOT NULL REFERENCES students(id),
  semester_no INT NOT NULL,
  sgpa        DECIMAL(4,2) NOT NULL,
  credits     INT NOT NULL,
  CONSTRAINT uq_sem_result UNIQUE (student_id, semester_no)
);
