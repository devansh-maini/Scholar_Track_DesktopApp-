-- V5: HOD department metrics & AI assistant persistence

-- HOD department performance snapshot (pre-computed per run)
CREATE TABLE department_performance_snapshots (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id BIGINT NOT NULL REFERENCES departments(id),
  snapshot_date DATE   NOT NULL,
  avg_attendance DECIMAL(5,2) NOT NULL,
  avg_marks      DECIMAL(5,2) NOT NULL,
  at_risk_count  INT NOT NULL DEFAULT 0,
  total_students INT NOT NULL DEFAULT 0,
  created_at     TIMESTAMP NOT NULL,
  CONSTRAINT uq_dept_snap UNIQUE (department_id, snapshot_date)
);
CREATE INDEX idx_dept_snap_dept ON department_performance_snapshots(department_id);

-- AI chat history per user
CREATE TABLE ai_chat_history (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users(id),
  session_id VARCHAR(80) NOT NULL,
  sender     VARCHAR(12) NOT NULL CHECK (sender IN ('USER', 'ASSISTANT')),
  content    VARCHAR(8000) NOT NULL,
  created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_ai_chat_user    ON ai_chat_history(user_id);
CREATE INDEX idx_ai_chat_session ON ai_chat_history(session_id);

-- AI study plans
CREATE TABLE ai_study_plans (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id  BIGINT NOT NULL REFERENCES students(id),
  generated_at TIMESTAMP NOT NULL,
  plan_json   TEXT NOT NULL,
  model_ver   VARCHAR(40) NOT NULL DEFAULT 'rule-v1'
);
CREATE INDEX idx_study_plan_student ON ai_study_plans(student_id);
