package com.scholartrack.report;

import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.FontFactory;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.Rectangle;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.time.LocalDate;
import java.util.List;
import java.util.Map;

final class PdfExporter {
    private PdfExporter() {}

    static byte[] export(ReportDoc doc) {
        boolean wide = doc.tables().stream().anyMatch(t -> t.headers().size() > 6);
        Document pdf = new Document(wide ? PageSize.A4.rotate() : PageSize.A4, 36, 36, 40, 36);
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        try {
            PdfWriter.getInstance(pdf, out);
            pdf.open();
            Font h1 = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 18, new Color(15, 23, 42));
            Font h2 = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 12, new Color(15, 118, 110));
            Font sub = FontFactory.getFont(FontFactory.HELVETICA, 9, new Color(100, 116, 139));
            Font bold = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10, new Color(30, 41, 59));
            Font body = FontFactory.getFont(FontFactory.HELVETICA, 9, new Color(30, 41, 59));
            Font head = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 9, Color.WHITE);

            pdf.add(new Paragraph("ScholarTrack", sub));
            pdf.add(new Paragraph(doc.title(), h1));
            if (doc.subtitle() != null && !doc.subtitle().isBlank()) pdf.add(new Paragraph(doc.subtitle(), sub));

            if (!doc.facts().isEmpty()) {
                PdfPTable facts = new PdfPTable(2);
                facts.setWidthPercentage(wide ? 45 : 65);
                facts.setHorizontalAlignment(Element.ALIGN_LEFT);
                facts.setSpacingBefore(10);
                for (Map.Entry<String, String> e : doc.facts().entrySet()) {
                    PdfPCell k = new PdfPCell(new Phrase(e.getKey(), bold));
                    PdfPCell v = new PdfPCell(new Phrase(nz(e.getValue()), body));
                    for (PdfPCell c : new PdfPCell[]{k, v}) { c.setBorder(Rectangle.BOTTOM); c.setBorderColor(new Color(226, 232, 240)); c.setPadding(4); }
                    facts.addCell(k); facts.addCell(v);
                }
                pdf.add(facts);
            }

            for (ReportDoc.Table t : doc.tables()) {
                Paragraph tp = new Paragraph(t.title(), h2);
                tp.setSpacingBefore(16); tp.setSpacingAfter(5);
                pdf.add(tp);
                if (t.rows().isEmpty()) { pdf.add(new Paragraph("No data.", sub)); continue; }
                PdfPTable table = new PdfPTable(t.headers().size());
                table.setWidthPercentage(100);
                table.setHeaderRows(1);
                for (String h : t.headers()) {
                    PdfPCell c = new PdfPCell(new Phrase(h, head));
                    c.setBackgroundColor(new Color(15, 118, 110)); c.setPadding(5);
                    table.addCell(c);
                }
                boolean zebra = false;
                for (List<String> row : t.rows()) {
                    for (String v : row) {
                        PdfPCell c = new PdfPCell(new Phrase(nz(v), body));
                        c.setPadding(4); c.setBorderColor(new Color(226, 232, 240));
                        if (zebra) c.setBackgroundColor(new Color(241, 245, 249));
                        table.addCell(c);
                    }
                    zebra = !zebra;
                }
                pdf.add(table);
            }
            Paragraph foot = new Paragraph("Generated by ScholarTrack on " + LocalDate.now() + ". Figures come from official records and fixed formulas.", sub);
            foot.setSpacingBefore(18);
            pdf.add(foot);
            pdf.close();
        } catch (DocumentException e) {
            throw new IllegalStateException("Could not build the PDF", e);
        }
        return out.toByteArray();
    }

    private static String nz(String s) { return s == null ? "" : s; }
}
